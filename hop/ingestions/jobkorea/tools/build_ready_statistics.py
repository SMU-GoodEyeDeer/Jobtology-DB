"""Generate the additive fresh-seal statistics refresh from canonical SQL006."""

import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[4]
OUTPUT = ROOT / "hop/ingestions/jobkorea/sql/008_ready_statistics.sql"
INSERTION = """ -- Bulk append may finish before automatic statistics collection. Refresh only
 -- the physical-row lookup columns once, after the complete-file guards; every
 -- manifest and READY validator below still reads the current evidence.
 ANALYZE ingestion.record (run_id,document_id,locator);
"""


def build() -> str:
    canonical = (ROOT / "hop/ingestions/jobkorea/sql/006_ndjson.sql").read_text()
    start = canonical.index("CREATE OR REPLACE FUNCTION ingestion.seal_jobkorea_ndjson_import(")
    end = canonical.index("\nEND $$;", start) + len("\nEND $$;")
    body = canonical[start:end]
    marker = " manifest:=ingestion.jobkorea_ndjson_row_manifest(p_run_id);"
    if body.count(marker) != 1:
        raise ValueError("Canonical seal manifest boundary differs")
    candidate = body.replace(marker, INSERTION + marker)
    # prosrc is exactly the text enclosed by the canonical dollar quotes.
    hashes = [
        hashlib.md5(sql.split("AS $$", 1)[1].rsplit("$$;", 1)[0].encode()).hexdigest()
        for sql in (body, candidate)
    ]
    guard = f"""DO $guard$ BEGIN
 IF NOT EXISTS(SELECT 1 FROM pg_proc p JOIN pg_language l ON l.oid=p.prolang
  WHERE p.oid=to_regprocedure('ingestion.seal_jobkorea_ndjson_import(text,text,bigint)')
  AND l.lanname='plpgsql' AND p.prokind='f' AND NOT p.prosecdef
  AND p.provolatile='v' AND p.proparallel='u' AND p.proconfig IS NULL
  AND pg_get_function_result(p.oid)='TABLE(state text, record_count bigint, issue_count bigint)'
  AND md5(p.prosrc) IN ('{hashes[0]}','{hashes[1]}'))
 THEN RAISE EXCEPTION 'JOBKOREA_SEAL_CANONICAL_DRIFT'; END IF;
END $guard$;
"""
    return (
        "-- Generated by tools/build_ready_statistics.py from the SQL006 seal body.\n"
        "-- Additive access-path fix; no validation result or source data is cached.\n"
        "-- READY replay returns through the original finalizer before this refresh.\n"
        "BEGIN;\nSELECT retention.gate();\n\n" + guard + candidate + "\n\nCOMMIT;\n"
    )


if __name__ == "__main__":
    OUTPUT.write_text(build())
