"""Generate the additive opt-in v3 contract without changing immutable v1/v2."""

# Exact historical SQL fragments deliberately retain their original whitespace.
# ruff: noqa: E501

import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[4]
SQL = ROOT / "hop/llm/sql"
PROMPTS = ROOT / "hop/llm/prompts"


def replace_once(text: str, old: str, new: str) -> str:
    if text.count(old) != 1:
        raise ValueError("Expected one exact migration fragment: " + old[:100])
    return text.replace(old, new, 1)


def function(filename: str, name: str) -> str:
    text = (SQL / filename).read_text()
    start = text.index("CREATE OR REPLACE FUNCTION enrichment." + name + "(")
    end = text.index("END $$;", start) + len("END $$;")
    return text[start:end]


def build() -> None:
    version = "ko-metadata-occupation-v3"
    prompt = (PROMPTS / "categorize-ko-metadata-occupation-v3.txt").read_text()
    schema = json.loads((PROMPTS / "categorize-ko-metadata-occupation-v3.schema.json").read_text())
    encoded = json.dumps(schema, ensure_ascii=False, separators=(",", ":"))
    digest = hashlib.sha256((prompt + "\n" + encoded).encode()).hexdigest()
    text = "-- Generated by tools/build_metadata_multimatch.py. Opt-in v3; immutable legacy rows remain unchanged.\nBEGIN;\n"
    identity = f"system_prompt=$v3prompt${prompt}$v3prompt$ AND output_schema=$v3schema${encoded}$v3schema$::jsonb AND content_hash='{digest}'"
    text += f"INSERT INTO enrichment.prompt(version,stage,system_prompt,output_schema,content_hash) VALUES ('{version}','categorize',$v3prompt${prompt}$v3prompt$,$v3schema${encoded}$v3schema$::jsonb,'{digest}') ON CONFLICT(version,stage) DO NOTHING;\n"
    text += f"DO $identity$ BEGIN IF NOT EXISTS(SELECT 1 FROM enrichment.prompt WHERE version='{version}' AND stage='categorize' AND {identity}) THEN RAISE EXCEPTION 'METADATA_PROMPT_VERSION_IS_IMMUTABLE'; END IF; END $identity$;\n"
    text += (
        ROOT / "hop/ingestions/jobkorea/tools/sql/metadata_occupation_multimatch_body.sql"
    ).read_text() + "\n"
    bind = function("033_metadata_occupation_roles.sql", "bind_metadata_occupation_item")
    bind = replace_once(
        bind,
        "'ko-metadata-occupation-v1','ko-metadata-occupation-v2'",
        "'ko-metadata-occupation-v1','ko-metadata-occupation-v2','ko-metadata-occupation-v3'",
    )
    text += bind + "\n"
    plan = function("034_metadata_occupation_pm.sql", "plan_metadata_occupation_batch")
    plan = replace_once(
        plan,
        "'ko-metadata-occupation-v1','ko-metadata-occupation-v2'",
        "'ko-metadata-occupation-v1','ko-metadata-occupation-v2','ko-metadata-occupation-v3'",
    )
    plan = replace_once(
        plan,
        "(opts->>'max_matches')::integer NOT BETWEEN 1 AND 2",
        "(opts->>'max_matches')::integer NOT BETWEEN 1 AND (CASE WHEN requested_prompt='ko-metadata-occupation-v3' THEN 3 ELSE 2 END)",
    )
    plan = replace_once(
        plan,
        "'validator','metadata-occupation-v1'",
        "'validator',CASE WHEN requested_prompt='ko-metadata-occupation-v3' THEN 'metadata-occupation-v3' ELSE 'metadata-occupation-v1' END",
    )
    plan = replace_once(
        plan,
        "AND d.decision='REJECT')",
        "AND d.decision='REJECT')\n   AND NOT EXISTS(SELECT 1 FROM enrichment.metadata_occupation_result r JOIN enrichment.metadata_occupation_candidate c USING(result_id)\n    JOIN LATERAL(SELECT decision FROM enrichment.metadata_occupation_candidate_decision d WHERE d.candidate_id=c.candidate_id ORDER BY decision_id DESC LIMIT 1) d ON true\n    WHERE r.attempt_id=old.attempt_id AND d.decision='REJECT')",
    )
    text += plan + "\n"
    response = function("030_metadata_occupation_native.sql", "save_response")
    response = replace_once(
        response,
        "errors:=enrichment.metadata_occupation_output_issues(output,i.source_data,a.candidates,\n      (b.settings->>'max_matches')::integer);",
        "errors:=CASE WHEN b.settings->>'prompt_version'='ko-metadata-occupation-v3'\n      THEN enrichment.metadata_occupation_output_issues_v3(output,i.source_data,a.candidates,(b.settings->>'max_matches')::integer)\n      ELSE enrichment.metadata_occupation_output_issues(output,i.source_data,a.candidates,(b.settings->>'max_matches')::integer) END;",
    )
    text += response + "\n"
    capture = function("029_metadata_occupation_links.sql", "capture_metadata_occupation_result")
    capture = replace_once(
        capture,
        "a enrichment.attempt%ROWTYPE;",
        "a enrichment.attempt%ROWTYPE; b enrichment.batch%ROWTYPE;",
    )
    capture = replace_once(
        capture,
        "SELECT * INTO STRICT binding",
        "SELECT * INTO STRICT b FROM enrichment.batch WHERE batch_id=i.batch_id;\n SELECT * INTO STRICT binding",
    )
    capture = replace_once(
        capture,
        "errors:=enrichment.metadata_occupation_output_issues(a.parsed_output,i.source_data,binding.candidates,2);",
        "errors:=CASE WHEN b.settings->>'prompt_version'='ko-metadata-occupation-v3'\n  THEN enrichment.metadata_occupation_output_issues_v3(a.parsed_output,i.source_data,binding.candidates,(b.settings->>'max_matches')::integer)\n  ELSE enrichment.metadata_occupation_output_issues(a.parsed_output,i.source_data,binding.candidates,2) END;",
    )
    text += capture + "\n"
    decision = function("029_metadata_occupation_links.sql", "decide_metadata_occupation")
    decision = replace_once(
        decision,
        "SELECT * INTO STRICT binding",
        "IF EXISTS(SELECT 1 FROM enrichment.item i JOIN enrichment.batch b USING(batch_id) WHERE i.item_id=r.item_id AND b.settings->>'prompt_version'='ko-metadata-occupation-v3') THEN RAISE EXCEPTION 'METADATA_OCCUPATION_CANDIDATE_REVIEW_REQUIRED'; END IF;\n SELECT * INTO STRICT binding",
    )
    text += decision + "\nCOMMIT;\n"
    text = text.removesuffix("COMMIT;\n")
    legacy = (SQL / "036_batchfree_graph_publication.sql").read_text()
    start = legacy.index("CREATE OR REPLACE FUNCTION enrichment.metadata_occupation_graph_rows(")
    end = legacy.index("$$;", start) + 3
    graph = legacy[start:end].replace(
        "enrichment.metadata_occupation_graph_rows(",
        "enrichment.metadata_occupation_graph_rows_legacy(",
    )
    graph = replace_once(
        graph,
        "enrichment.metadata_occupation_status(jobs,ncs)",
        "enrichment.metadata_occupation_publication_results(jobs,ncs)",
    )
    graph = replace_once(
        graph,
        "WHERE r.output->>'outcome'='matched'",
        "WHERE b.settings->>'prompt_version'<>'ko-metadata-occupation-v3' AND r.output->>'outcome'='matched'",
    )
    text += graph + "\n"
    text += """CREATE OR REPLACE FUNCTION enrichment.metadata_occupation_graph_rows(jobs text,ncs text,include_unreviewed boolean DEFAULT false)
RETURNS TABLE(posting_id text,posting_identity text,occupation_identity text,candidate_id text,payload jsonb)
LANGUAGE sql STABLE AS $$
 SELECT * FROM enrichment.metadata_occupation_graph_rows_legacy(jobs,ncs,include_unreviewed)
 UNION ALL SELECT * FROM enrichment.metadata_occupation_graph_rows_v3(jobs,ncs,include_unreviewed)
$$;
"""
    status = (SQL / "035_metadata_occupation_terminal_status.sql").read_text()
    status = status[status.index("CREATE OR REPLACE FUNCTION") : status.index("COMMIT;")]
    status = replace_once(
        status,
        "i.categorization_id FROM",
        "i.categorization_id,b.settings->>'prompt_version' AS prompt_version FROM",
    )
    status = replace_once(
        status,
        "WHEN d.decision IS NULL THEN 'REVIEW_PENDING'",
        "WHEN d.decision IS NULL AND b.prompt_version='ko-metadata-occupation-v3' AND EXISTS(SELECT 1 FROM enrichment.metadata_occupation_candidate_status(r.result_id) WHERE decision IS NOT NULL) THEN 'PARTIALLY_REVIEWED'\n   WHEN d.decision IS NULL THEN 'REVIEW_PENDING'",
    )
    status = replace_once(
        status,
        "SELECT d.* FROM enrichment.metadata_occupation_decision d WHERE d.result_id=r.result_id\n  ORDER BY decision_id DESC LIMIT 1",
        "SELECT decision FROM (SELECT d.decision,d.decision_id FROM enrichment.metadata_occupation_decision d WHERE d.result_id=r.result_id AND b.prompt_version<>'ko-metadata-occupation-v3'\n  UNION ALL SELECT CASE WHEN bool_and(s.decision='REJECT') AND count(s.decision)=count(*) THEN 'REJECT'\n   WHEN count(*) FILTER(WHERE s.decision='ACCEPT')>0 AND count(*) FILTER(WHERE s.decision IS NULL)=0 THEN 'ACCEPT' END,0\n   FROM enrichment.metadata_occupation_candidate_status(r.result_id) s WHERE b.prompt_version='ko-metadata-occupation-v3' HAVING count(*)>0) latest ORDER BY decision_id DESC LIMIT 1",
    )
    text += status + "\nCOMMIT;\n"
    (SQL / "037_metadata_occupation_multimatch.sql").write_text(text)


if __name__ == "__main__":
    build()
