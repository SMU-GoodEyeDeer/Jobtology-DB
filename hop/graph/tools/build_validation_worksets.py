"""Generate narrow document counts and Nara conflict worksets from frozen SQL003.

The public rules, wrapper fallback authority, proof algorithms and other source
conflict branches remain unchanged. This migration changes one exact-run helper.
"""

from __future__ import annotations

import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
SOURCE = ROOT / "hop/graph/sql/003_source_query_sharing.sql"
OUTPUT = ROOT / "hop/graph/sql/005_validation_worksets.sql"
SOURCE_SHA256 = "761ecb278d4db00396128e00fa2290973928a4c1be3cd0c3796a456cf441beff"
NAME = "ingestion.source_graph_scoped_validation_issue(jobs text)"

ROW_COUNTS_BEFORE = """SELECT d.run_id, 'ROW_COUNT_MISMATCH', d.document_id FROM selected d
WHERE d.item_count IS DISTINCT FROM (
    (SELECT count(*) FROM records r
     WHERE r.run_id = d.run_id AND r.document_id = d.document_id)
  + (SELECT count(*) FROM rejected e
     WHERE e.run_id = d.run_id AND e.document_id = d.document_id))"""
ROW_COUNTS_AFTER = """SELECT d.run_id, 'ROW_COUNT_MISMATCH', d.document_id FROM selected d
LEFT JOIN record_rows r USING(run_id,document_id)
LEFT JOIN rejected_rows e USING(run_id,document_id)
WHERE d.item_count IS DISTINCT FROM coalesce(r.rows,0)+coalesce(e.rows,0)"""
CONFLICT_BEFORE = """SELECT l.run_id,'NARA_POSTING_CONFLICT',l.normalized->>'posting_id'
FROM facts l JOIN runs u ON u.run_id=l.run_id AND u.source_id='nara_job'
JOIN facts d ON d.run_id=l.run_id AND d.normalized->>'posting_id'=l.normalized->>'posting_id'
 AND d.normalized->>'representation'='detail'
WHERE l.normalized->>'representation'='list'
 AND nullif(d.normalized->>'title','') IS NOT NULL
 AND l.normalized->>'title' IS DISTINCT FROM d.normalized->>'title'"""
CONFLICT_AFTER = """SELECT g.run_id,'NARA_POSTING_CONFLICT',g.posting_id
FROM nara_conflict_groups g
CROSS JOIN LATERAL unnest(g.list_titles) l(title)
CROSS JOIN LATERAL unnest(g.detail_titles) d(title)
WHERE nullif(d.title,'') IS NOT NULL AND l.title IS DISTINCT FROM d.title"""
WORKSETS = """nara_conflict_facts AS MATERIALIZED (
 SELECT f.run_id,f.normalized->>'posting_id' AS posting_id,
 f.normalized->>'representation' AS representation,f.normalized->>'title' AS title
 FROM facts f JOIN runs u USING(run_id) WHERE u.source_id='nara_job'
), nara_conflict_groups AS (
 SELECT run_id,posting_id,
 array_agg(title) FILTER(WHERE representation='list') AS list_titles,
 array_agg(title) FILTER(WHERE representation='detail') AS detail_titles
 FROM nara_conflict_facts WHERE posting_id IS NOT NULL
 GROUP BY run_id,posting_id
)
"""


def replace_once(source: str, before: str, after: str) -> str:
    if source.count(before) != 1:
        raise ValueError("Frozen SQL003 replacement contract changed")
    return source.replace(before, after)


def definition(source: str) -> str:
    start = source.index("CREATE OR REPLACE FUNCTION " + NAME)
    stop = source.index("$$;", start) + 3
    return source[start:stop]


def body(function: str) -> str:
    return function.split("AS $$", 1)[1].rsplit("$$;", 1)[0]


def candidate(source: str) -> str:
    result = definition(source)
    anchor = "rejected AS MATERIALIZED (SELECT * FROM ingestion.rejected_row WHERE run_id=jobs),\n"
    result = replace_once(
        result,
        anchor,
        anchor
        + "record_rows AS MATERIALIZED (SELECT run_id,document_id,count(*) AS rows FROM records\n"
        + " GROUP BY run_id,document_id),\n"
        + "rejected_rows AS MATERIALIZED (SELECT run_id,document_id,count(*) AS rows "
        + "FROM rejected\n"
        + " GROUP BY run_id,document_id),\n",
    )
    result = replace_once(result, ROW_COUNTS_BEFORE, ROW_COUNTS_AFTER)
    result = replace_once(result, CONFLICT_BEFORE, CONFLICT_AFTER)
    result = replace_once(
        result,
        ")\nSELECT u.run_id, 'SMOKE_NOT_FULL'",
        "), " + WORKSETS + "SELECT u.run_id, 'SMOKE_NOT_FULL'",
    )
    return result


def build() -> str:
    data = SOURCE.read_bytes()
    if hashlib.sha256(data).hexdigest() != SOURCE_SHA256:
        raise ValueError("Frozen SQL003 SHA256 changed")
    source = data.decode()
    old, new = definition(source), candidate(source)
    # pg_proc.prosrc is the exact text between dollar delimiters. Reinstallation
    # accepts only frozen003 or this exact005, with the original execution flags.
    old_hash = hashlib.md5(body(old).encode()).hexdigest()
    new_hash = hashlib.md5(body(new).encode()).hexdigest()
    return (
        "-- Generated by graph/tools/build_validation_worksets.py from frozen SQL003.\n"
        "-- Group only document counts and Nara text-title pairs; preserve issue bags.\n"
        "BEGIN;\n"
        "DO $guard$ BEGIN\n"
        " IF NOT EXISTS(SELECT 1 FROM pg_proc p WHERE\n"
        "  p.oid='ingestion.source_graph_scoped_validation_issue(text)'::regprocedure\n"
        f"  AND md5(p.prosrc) IN ('{old_hash}','{new_hash}')\n"
        "  AND p.provolatile='s' AND p.proparallel='u' AND NOT p.proisstrict\n"
        "  AND NOT p.prosecdef AND NOT p.proleakproof AND p.proretset\n"
        "  AND p.prolang=(SELECT oid FROM pg_language WHERE lanname='sql')\n"
        "  AND p.prorettype='record'::regtype AND p.pronargdefaults=0\n"
        "  AND p.proallargtypes=ARRAY[25,25,25,25]::oid[]\n"
        "  AND p.proargnames=ARRAY['jobs','run_id','issue','location']::text[]\n"
        "  AND p.proargmodes=ARRAY['i','t','t','t']::\"char\"[]\n"
        "  AND p.proconfig=ARRAY['jit=off']::text[]) THEN\n"
        "  RAISE EXCEPTION 'SOURCE_GRAPH_VALIDATION_WORKSET_BASELINE_DRIFT';\n"
        " END IF;\nEND $guard$;\n\n"
        + new
        + "\nCOMMIT;\n"
    )


if __name__ == "__main__":
    OUTPUT.write_text(build())
