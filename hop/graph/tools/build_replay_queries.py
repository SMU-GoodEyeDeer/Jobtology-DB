"""Build the additive verified-proof replay fast path from frozen SQL003."""

import hashlib
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
OUTPUT = ROOT / 'hop/graph/sql/004_verified_proof_replay.sql'
PUBLIC = 'ingestion.begin_source_graph_projection'
COMPAT = 'ingestion.begin_source_graph_projection_v3_compat'
BODY = '''
DECLARE u ingestion.run; p ingestion.source_graph_projection;
BEGIN
 -- Acquire the retention gate before live reads or proof row locks. This
 -- prevents archival between eligibility validation and replay publication.
 PERFORM retention.gate();
 -- Retained archived proofs are valid for readback, never a new live replay.
 SELECT * INTO u FROM ingestion.run WHERE run_id=jobs AND state='READY' AND mode<>'SMOKE';
 IF NOT FOUND THEN RAISE EXCEPTION 'SOURCE_GRAPH_REQUIRES_EXACT_READY_RUN'; END IF;
 SELECT * INTO p FROM ingestion.source_graph_projection WHERE run_id=jobs FOR UPDATE;
 IF FOUND
  AND p.record_count=(SELECT count(*) FROM ingestion.source_graph_record_evidence WHERE run_id=jobs)
  AND p.reference_count=(SELECT count(*) FROM ingestion.source_graph_membership WHERE run_id=jobs)
 THEN
  -- Authoritative validation still compares captured and live content, before
  -- changing state. UPDATE retains immutable-proof and retention guards.
  PERFORM ingestion.assert_source_graph_content(jobs);
  UPDATE ingestion.source_graph_projection SET state='LOADING',verified_at=NULL,
   error_code=NULL,started_at=clock_timestamp() WHERE run_id=jobs;
  RETURN true;
 END IF;
 -- First capture and incomplete captured rows keep the exact SQL003 behavior.
 RETURN ingestion.begin_source_graph_projection_v3_compat(jobs);
END '''


def build() -> str:
    source = (ROOT / 'hop/graph/sql/003_source_query_sharing.sql').read_text()
    match = re.search(
        r'CREATE OR REPLACE FUNCTION ingestion\.begin_source_graph_projection\(jobs text\) '
        r'RETURNS boolean\nLANGUAGE plpgsql SET jit=off AS \$\$([\s\S]*?)\$\$;', source)
    if match is None:
        raise ValueError('Frozen SQL003 begin contract missing')
    original = match[1]
    hashes = [hashlib.md5(body.encode()).hexdigest() for body in (original, BODY)]
    guard = f'''DO $guard$ BEGIN
 IF NOT EXISTS(SELECT 1 FROM pg_proc p JOIN pg_language l ON l.oid=p.prolang
  WHERE p.oid='{PUBLIC}(text)'::regprocedure AND l.lanname='plpgsql'
  AND p.prorettype='boolean'::regtype AND NOT p.prosecdef
  AND p.proconfig=ARRAY['jit=off']::text[] AND md5(p.prosrc) IN ('{hashes[0]}','{hashes[1]}'))
 THEN RAISE EXCEPTION 'SOURCE_GRAPH_REPLAY_CANONICAL_DRIFT'; END IF;
END $guard$;
'''
    return ('-- Generated by tools/build_replay_queries.py; SQL003 stays frozen.\n'
            '-- Existing complete proofs validate once; first/incomplete capture is unchanged.\n'
            'BEGIN;\n' + guard +
            f'CREATE OR REPLACE FUNCTION {COMPAT}(jobs text) RETURNS boolean\n'
            'LANGUAGE plpgsql SET jit=off AS $$' + original + '$$;\n\n' +
            f'CREATE OR REPLACE FUNCTION {PUBLIC}(jobs text) RETURNS boolean\n'
            'LANGUAGE plpgsql SET jit=off AS $$' + BODY + '$$;\nCOMMIT;\n')


if __name__ == '__main__':
    OUTPUT.write_text(build())
